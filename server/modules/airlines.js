/** Une immatriculation (F-GKRT) utilisée comme indicatif = aviation générale. */
export function airlineFor(callsign, reg) {
  if (!callsign) return null;
  const regNoDash = (reg || '').replace('-', '');
  if (regNoDash && callsign === regNoDash) return 'Privé';
  const m = /^([A-Z]{3})\d/.exec(callsign);
  if (m) return AIRLINES[m[1]] || m[1];
  return /^[A-Z]{1,2}[A-Z]{3,4}$/.test(callsign) ? 'Privé' : null;
}
